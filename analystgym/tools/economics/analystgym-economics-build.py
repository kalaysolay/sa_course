rate = 1500
fee, refunds = .03, .05
review_cost = 2
products = {
 'main': dict(name='Основной курс', price=20000, kzt=100000, reviews=200, other=100, hours=.5),
 'sdd': dict(name='Курс SDD', price=5000, kzt=25000, reviews=60, other=30, hours=.25),
 'pro': dict(name='Тренажёр за месяц', price=990, kzt=5000, reviews=40, other=10, hours=.05),
}
for p in products.values():
    p['llm'] = p['reviews'] * review_cost
    p['cash_margin'] = p['price'] * (1-fee-refunds) - p['llm'] - p['other']
    p['labor'] = p['hours'] * rate
    p['contribution'] = p['cash_margin'] - p['labor']

def scenario(main, sdd, pro, ads, free):
    counts = dict(main=main, sdd=sdd, pro=pro)
    gross = sum(products[k]['price']*v for k,v in counts.items())
    variables = sum((products[k]['price']*(fee+refunds)+products[k]['llm']+products[k]['other'])*v for k,v in counts.items())
    support_hours = sum(products[k]['hours']*v for k,v in counts.items())
    free_cost = free*2*review_cost
    cash = gross - variables - 5000 - ads - free_cost
    labor = (20+support_hours)*rate
    return dict(counts=counts,gross=gross,variables=variables,ads=ads,infra=5000,free_cost=free_cost,
                cash=cash,hours=20+support_hours,labor=labor,economic=cash-labor)

