def table(headers,rows,widths):
    t=doc.add_table(rows=1, cols=len(headers));t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
    for c,w in zip(t.columns,widths):c.width=Cm(w)
    for c,h in zip(t.rows[0].cells,headers):c.text=str(h)
    for row in rows:
        cells=t.add_row().cells
        for c,value in zip(cells,row):c.text=str(value)
    for ri,row in enumerate(t.rows):
        trpr=row._tr.get_or_add_trPr()
        cant=OxmlElement('w:cantSplit');trpr.append(cant)
        if ri==0:
            repeat=OxmlElement('w:tblHeader');trpr.append(repeat)
        for ci,c in enumerate(row.cells):
            c.width=Cm(widths[ci]);c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr=c._tc.get_or_add_tcPr()
            sh=OxmlElement('w:shd');sh.set(qn('w:fill'),'243746' if ri==0 else ('F2F5F7' if ri%2 else 'FFFFFF'));pr.append(sh)
            borders=OxmlElement('w:tcBorders')
            for edge in ['top','left','bottom','right']:
                b=OxmlElement('w:'+edge);b.set(qn('w:val'),'single');b.set(qn('w:sz'),'4');b.set(qn('w:color'),'D9D9D9');borders.append(b)
            pr.append(borders)
            margins=OxmlElement('w:tcMar')
            for edge,value in [('top','85'),('bottom','85'),('left','100'),('right','100')]:
                item=OxmlElement('w:'+edge);item.set(qn('w:w'),value);item.set(qn('w:type'),'dxa');margins.append(item)
            pr.append(margins)
            for p in c.paragraphs:
                p.paragraph_format.space_after=Pt(1);p.paragraph_format.line_spacing=1.0
                p.alignment=WD_ALIGN_PARAGRAPH.LEFT if ci==0 else WD_ALIGN_PARAGRAPH.CENTER
                for run in p.runs:
                    run.font.name='Arial';run.font.size=Pt(9)
                    run.bold=ri==0;run.font.color.rgb=RGBColor(255,255,255) if ri==0 else RGBColor(0,0,0)
    doc.add_paragraph().paragraph_format.space_after=Pt(0)
    def md_cell(value): return str(value).replace('|','\\|').replace('\n','<br>')
    md.append('| '+' | '.join(md_cell(h) for h in headers)+' |')
    md.append('| '+' | '.join(['---']*len(headers))+' |')
    for row in rows:md.append('| '+' | '.join(md_cell(value) for value in row)+' |')
    md.append('')
