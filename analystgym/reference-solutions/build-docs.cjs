// Проверяем внутренние ссылки до записи или проверки файлов на диске.
for (const [file,content] of generated) {
 if(content.includes('\uFFFD')) throw new Error('Повреждённый UTF-8 '+file);
 if(!file.endsWith('.md')) continue;
 for(const match of content.matchAll(/\]\(([^)]+)\)/g)) {
  const link=match[1]; if(/^[a-z]+:|^#/.test(link)) continue;
  const target=path.normalize(path.join(path.dirname(file),link)).replaceAll('\\','/');
  if(!generated.has(target) && !fs.existsSync(path.join(root,target))) throw new Error('Неразрешимая ссылка '+file+' -> '+link);
 }
}
const check=process.argv.includes('--check');
for (const [file,content] of generated) {
 const target=path.join(root,file);
 if(check) {if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content) throw new Error('Файл отсутствует или не соответствует источнику: '+file);}
 else {fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,content,'utf8');}
}
console.log(JSON.stringify({mode:check?'check':'build',tasks:ids.length,questions:total,files:generated.size,markdownFiles:[...generated.keys()].filter(p=>p.endsWith('.md')).length,status:'ok'}));
