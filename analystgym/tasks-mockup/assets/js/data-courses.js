/* Заглушка урока без готового контента: навигация есть, тело — «в производстве» */
function L(id, title) {
  return { id, title, minutes: null, free: false, filled: false };
}

SA_DATA.flatLessons = function (course) {
  if (!course) return [];
  if (course.modules) {
    const out = [];
    course.modules.forEach((module) => {
      (module.sections || []).forEach((section) => {
        (section.lessons || []).forEach((lesson) => {
          out.push(Object.assign({ moduleId: module.id, moduleTitle: module.title, sectionId: section.id, sectionTitle: section.title }, lesson));
        });
      });
    });
    return out;
  }
  return (course.lessons || []).slice();
};

